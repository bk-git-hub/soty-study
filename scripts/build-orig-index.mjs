// Maps "ln-home-horiz-1.webp" -> "68302baa04b14a1ca33c0b25_ln-home-horiz-1.webp" for every file in public/orig/cdn.
import { readdirSync, writeFileSync } from 'node:fs';
const files = readdirSync('public/orig/cdn');
const map = {};
for (const f of files) {
  const short = decodeURIComponent(f.replace(/^[0-9a-f]{24}_/, ''));
  map[short] = f;
}
writeFileSync('src/data/orig-index.js', '// generated by scripts/build-orig-index.mjs (gitignored)\nexport default ' + JSON.stringify(map, null, 1) + ';\n');
console.log('indexed', Object.keys(map).length, 'assets');
